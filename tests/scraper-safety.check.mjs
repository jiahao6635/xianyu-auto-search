import assert from 'node:assert/strict';
import { XianyuScraper } from '../src/lib/xianyu-scraper.ts';
import { CollectionPausedError, FilterNotAppliedError } from '../src/lib/collection-safety.ts';
const scraper=new XianyuScraper();
const invisible={count:async()=>0,isVisible:async()=>false,filter(){return this;},first(){return this;}};
const page={locator:()=>invisible,getByText:()=>invisible,url:()=> 'https://www.goofish.com/search'};
await scraper.assertAccessible(page,'正常页面');
const challenged={...page,locator:()=>({count:async()=>1,nth:()=>({isVisible:async()=>true})})};
await assert.rejects(scraper.assertAccessible(challenged,'打开搜索页'),CollectionPausedError);
const login={...page,url:()=> 'https://www.goofish.com/login'};
await assert.rejects(scraper.assertAccessible(login,'筛选后'),CollectionPausedError);
let attempts=0;
scraper.applyRegionFilterAttempt=async()=>{attempts++;return false;};
page.waitForTimeout=async()=>{};
page.keyboard={press:async()=>{}};
await assert.rejects(scraper.applyRegionFilter(page,'省','市'),FilterNotAppliedError);
assert.equal(attempts,3);
await assert.rejects(scraper.selectDropdownOption(page,'新发布','最新'),FilterNotAppliedError);
await assert.rejects(scraper.fillPriceRange(page,1000,10000),FilterNotAppliedError);
console.log('6 scraper safety checks passed; no browser/database/network calls');
// Exercise the real search boundary: an extraction/DOM failure must not become an empty baseline.
let closed=false;
const emptyPage={...page,on(){},goto:async()=>{},waitForLoadState:async()=>{},title:async()=>'',close:async()=>{closed=true;}};
scraper.context={newPage:async()=>emptyPage};
scraper.applySearchFilters=async()=>{};
scraper.saveDebugArtifacts=async()=>{};
scraper.extractProducts=async()=>[];
await assert.rejects(scraper.search({keyword:'摩托车'}),FilterNotAppliedError);
assert.equal(closed,true);
console.log('Empty-result baseline guard also passed');
emptyPage.getByText=text=> text instanceof RegExp && text.source.includes('没有找到')
  ? {...invisible,isVisible:async()=>true} : invisible;
assert.deepEqual(await scraper.search({keyword:'摩托车'}),[]);
console.log('Confirmed empty-page acceptance passed: 8 safety scenarios total');
// Province-only requests must select the whole province and verify the applied summary.
const provinceScraper=new XianyuScraper();
let regionClicks=[];
const regionNode={...invisible,count:async()=>1,scrollIntoViewIfNeeded:async()=>{},click:async()=>{},waitFor:async()=>{}};
const provincePage={...page,locator:()=>({...regionNode,allTextContents:async()=>['河北']}),getByText:()=>({...invisible,waitFor:async()=>{}})};
provinceScraper.clickRegionOption=async(_page,label)=>{regionClicks.push(label);return true;};
provinceScraper.clickRegionConfirmButton=async()=>true;
assert.equal(await provinceScraper.applyRegionFilterAttempt(provincePage,1,'河北'),true);
assert.deepEqual(regionClicks,['河北','全河北']);
provinceScraper.clickRegionOption=async(_page,label)=>label!=='全河北';
await assert.rejects(provinceScraper.applyRegionFilterAttempt(provincePage,1,'河北'),/不回退城市或全国/);
provinceScraper.clickRegionOption=async()=>true;
const cityPage={...provincePage,locator:()=>({...regionNode,allTextContents:async()=>['河北 / 石家庄']})};
await assert.rejects(provinceScraper.applyRegionFilterAttempt(cityPage,1,'河北'),/无法确认河北全省/);
console.log('Hebei whole-province scenarios passed: 11 safety scenarios total');
